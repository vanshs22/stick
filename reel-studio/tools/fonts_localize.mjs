#!/usr/bin/env node
// Bundle the curated fonts (engine/fonts.ts) as local woff2 files so a render never waits on Google Fonts (offline, proxied or Kaggle).
//   NODE_USE_ENV_PROXY=1 node tools/fonts_localize.mjs        needs internet once; writes remotion-template/public/fonts/** and src/engine/fonts.local.ts
// Only the latin subset of the weights each font declares is fetched. All fonts are open licence (OFL / Apache).
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const TK = path.join(path.dirname(fileURLToPath(import.meta.url)), '..'), T = path.join(TK, 'remotion-template'), req = createRequire(path.join(T, 'package.json'));
const src = fs.readFileSync(path.join(T, 'src/engine/fonts.ts'), 'utf8');
const specs = [...src.matchAll(/(\w+): \{load: (\w+), weights: \[([^\]]*)\](?:, italic: true)?/g)].map((m) => ({ name: m[1], mod: m[2], weights: m[3].replace(/['\s]/g, '').split(','), italic: /italic: true/.test(m[0]) }));
const imp = Object.fromEntries([...src.matchAll(/import \{loadFont as (\w+)\} from '@remotion\/google-fonts\/(\w+)'/g)].map((m) => [m[1], m[2]]));
const local = {}; let bytes = 0, n = 0;
for (const s of specs) {
  const info = req(path.join(T, `node_modules/@remotion/google-fonts/dist/cjs/${imp[s.mod]}.js`)).getInfo(), faces = [];
  for (const [style, ws] of [['normal', s.weights], ...(s.italic ? [['italic', s.weights.slice(0, 1)]] : [])]) for (const w of ws) {
    const url = info.fonts?.[style]?.[w]?.latin; if (!url) { console.error(`skip ${s.name} ${style} ${w}: no latin file`); continue; }
    const rel = `fonts/${s.name}/${style}-${w}.woff2`, f = path.join(T, 'public', rel);
    if (!fs.existsSync(f)) { const r = await fetch(url); if (!r.ok) throw new Error(`${url}: ${r.status}`); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, Buffer.from(await r.arrayBuffer())); }
    bytes += fs.statSync(f).size; n++; faces.push({ style, weight: w, file: rel });
  }
  local[s.name] = { family: info.fontFamily, faces };
}
fs.writeFileSync(path.join(T, 'src/engine/fonts.local.ts'), `// generated by tools/fonts_localize.mjs: local woff2 files in public/fonts (no network at render time)\nexport const LOCAL_FONTS: Record<string, {family: string; faces: {style: string; weight: string; file: string}[]}> = ${JSON.stringify(local, null, 1)};\n`);
console.log(`${n} font files, ${(bytes / 1048576).toFixed(1)} MB, ${Object.keys(local).length} families -> remotion-template/public/fonts`);
